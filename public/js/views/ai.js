// Gemini image generation UI: idle, loading (cancellable), success (use / download / retry) and error (retry) states.
import { $, esc, ic } from '../core/util.js';
import { st, route } from '../core/state.js';
import { on } from '../core/actions.js';
import { toast, openDlg, dlg, downloadBlob } from '../core/ui.js';
import { generateImage, loadConfig } from '../services/api.js';
import { newDoc } from '../model.js';
import { store } from '../storage.js';
import { addImageEl, shrinkImage } from '../editor.js';
import { slug } from '../core/util.js';

const ASPECTS = [['1:1', 'Square 1:1', 1080, 1080], ['3:4', 'Portrait 3:4', 810, 1080], ['4:3', 'Landscape 4:3', 1080, 810], ['9:16', 'Tall 9:16', 1080, 1920], ['16:9', 'Wide 16:9', 1920, 1080]];
const dataUrl = (i) => `data:${i.mimeType};base64,${i.data}`;

export function aiPanel() {
  const a = st.ai;
  return `<section class="prompt" aria-labelledby="pl"><label class="t" id="pl" for="pi">Describe the image you want</label>
  <textarea id="pi" rows="3" maxlength="1000" placeholder="A watercolour banner of marigold flowers for a festival poster" aria-describedby="pn">${esc(a.prompt)}</textarea>
  <p class="hint" id="pn">Generated by Google Gemini through this site's server. Your prompt is sent to Google; nothing is generated in your browser.</p>
  <div class="pr"><label class="fld" style="flex-direction:row;align-items:center;gap:8px"><span>Shape</span><select id="pa" style="min-height:40px;border:1px solid var(--line);border-radius:8px;padding:0 8px">${ASPECTS.map((x) => `<option value="${x[0]}" ${x[0] === a.aspect ? 'selected' : ''}>${x[1]}</option>`).join('')}</select></label>
  <button class="btn p" data-act="ai-gen" id="aiGo">${ic('spark')}Generate image</button></div>
  <div id="aiOut" aria-live="polite">${outHTML()}</div></section>`;
}
function outHTML() {
  const a = st.ai, ed = route().n === 'editor' && st.doc;
  if (a.status === 'loading') return `<div class="note"><p><strong>Generating…</strong> This can take 10–40 seconds.</p><div><button class="btn s" data-act="ai-cancel">Cancel</button></div></div>`;
  if (a.status === 'err') return `<div class="note" role="alert"><p class="err">${esc(a.error.message)}</p><div><button class="btn s" data-act="ai-gen">${ic('refresh')}${a.error.retryable ? 'Retry' : 'Try again'}</button></div></div>`;
  if (a.status === 'ok') return `<div class="aires"><img src="${dataUrl(a.image)}" alt="${esc(a.prompt)}"><div class="chips"><button class="btn p s" data-act="ai-use">${ed ? 'Add to this design' : 'Start a design with it'}</button><button class="btn s" data-act="ai-dl">${ic('dl')}Download</button><button class="btn s" data-act="ai-gen">${ic('refresh')}Regenerate</button></div><p class="hint">AI-generated image. Check it before printing.</p></div>`;
  return '';
}
function paint() { const o = $('#aiOut'); if (o) o.innerHTML = outHTML(); const g = $('#aiGo'); if (g) g.disabled = st.ai.status === 'loading'; }

on('ai-open', async () => {
  const cfg = await loadConfig();
  openDlg('Generate an image with Gemini', aiPanel() + (cfg.gemini.configured ? '' : `<p class="err">Image generation is not configured on this server (GEMINI_API_KEY missing). See README.</p>`));
});
on('ai-gen', async () => {
  const a = st.ai, p = $('#pi'); a.prompt = p.value.trim(); a.aspect = $('#pa').value;
  if (!a.prompt) { a.status = 'err'; a.error = { message: 'Describe the image you want first.', retryable: false }; paint(); p.focus(); return; }
  a.ctl && a.ctl.abort(); a.ctl = new AbortController(); a.status = 'loading'; a.image = null; paint();
  const ctl = a.ctl;
  try { const img = await generateImage(a.prompt, a.aspect, ctl.signal); if (a.ctl !== ctl) return; a.image = img; a.status = 'ok'; }
  catch (e) { if (a.ctl !== ctl) return; if (e.code === 'cancelled') { a.status = 'idle'; } else { a.status = 'err'; a.error = { message: e.message, retryable: !!e.retryable }; } }
  paint();
});
on('ai-cancel', () => { st.ai.ctl && st.ai.ctl.abort(); });
on('ai-dl', async () => {
  const i = st.ai.image; if (!i) return;
  const bin = atob(i.data), u8 = Uint8Array.from(bin, (c) => c.charCodeAt(0)), ext = i.mimeType.split('/')[1].replace('jpeg', 'jpg');
  downloadBlob(`${slug(st.ai.prompt.slice(0, 40))}.${ext}`, new Blob([u8], { type: i.mimeType }));
});
on('ai-use', async () => {
  const i = st.ai.image; if (!i) return;
  try {
    if (route().n === 'editor' && st.doc) { await addImageEl(dataUrl(i), 'AI image', st.ai.prompt); if (dlg.open) dlg.close(); toast('Image added to the design.'); return; }
    const [, , w, h] = ASPECTS.find((x) => x[0] === st.ai.aspect) || ASPECTS[0], src = await shrinkImage(dataUrl(i));
    const d = newDoc('AI image design', w, h, '#FFFFFF', [{ id: 'img_ai1', type: 'image', name: 'AI image', x: 0, y: 0, w, h, opacity: 1, src, alt: st.ai.prompt.slice(0, 200), fit: 'cover' }], { origin: 'ai', prompt: st.ai.prompt });
    const r = store.save(d); if (!r.ok) return toast(r.error, true);
    location.hash = '#/editor/' + encodeURIComponent(d.id);
  } catch (e) { toast(e.message, true); }
});
